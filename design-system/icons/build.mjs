// Builds src/ui/Icon/icons.ts from the Carbon SVGs in carbon/, as path data with no markup strings.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export class IconSource {
  static parse(name, svg) {
    if (!svg.includes('viewBox="0 0 32 32"'))
      throw new Error(`${name}: expected a 32px Carbon icon`);
    // A circle becomes the same shape as two arcs, so every icon is path data.
    const body = svg
      .replace(/^\s*<svg[^>]*>|<\/svg>\s*$/g, "")
      .replace(
        /<circle\s+cx="([\d.]+)"\s+cy="([\d.]+)"\s+r="([\d.]+)"\s*\/>/g,
        (_, cx, cy, r) =>
          `<path d="M${+cx - +r},${cy}a${r},${r},0,1,0,${2 * r},0a${r},${r},0,1,0,${-2 * r},0Z"/>`,
      );
    const leftover = body.replace(/<path\s[^>]*\/>/g, "").trim();
    if (leftover)
      throw new Error(`${name}: unsupported markup ${leftover.slice(0, 40)}`);
    return [...body.matchAll(/<path\s([^>]*)\/>/g)].map(([, attrs]) => {
      const d = /\bd="([^"]+)"/.exec(attrs)?.[1];
      if (!d) throw new Error(`${name}: a path without d`);
      return /fill-rule="evenodd"/.test(attrs) ? { d, evenOdd: true } : { d };
    });
  }

  static module(icons) {
    const entries = Object.entries(icons).map(
      ([name, paths]) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths)},`,
    );
    return `// Generated by design-system/icons/build.mjs from IBM Carbon icons (Apache 2.0). Do not edit.\nexport const ICONS = {\n${entries.join("\n")}\n} as const satisfies Record<string, readonly { d: string; evenOdd?: boolean }[]>;\n\nexport type IconName = keyof typeof ICONS;\n`;
  }

  static load(dir) {
    const files = readdirSync(dir)
      .filter((file) => file.endsWith(".svg"))
      .sort();
    return Object.fromEntries(
      files.map((file) => {
        const name = file.replace(/\.svg$/, "");
        return [
          name,
          IconSource.parse(name, readFileSync(new URL(file, dir), "utf8")),
        ];
      }),
    );
  }
}

export const SOURCE = new URL("./carbon/", import.meta.url);
export const OUTPUT = new URL("../../src/ui/Icon/icons.ts", import.meta.url);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const icons = IconSource.load(SOURCE);
  writeFileSync(OUTPUT, IconSource.module(icons));
  console.log(
    `Wrote ${Object.keys(icons).length} icons to src/ui/Icon/icons.ts`,
  );
}
